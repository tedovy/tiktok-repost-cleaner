root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "_locales")
for lang, values in L.items():
    assert len(values) == len(KEYS), (lang, len(values))
    data = {}
    for key, text in zip(KEYS, values):
        entry: dict = {"message": text}
        if key == "btnLast":
            assert "$COUNT$" in text, lang
            entry["placeholders"] = {"count": {"content": "$1", "example": "10"}}
        if key in ("found", "throttled", "of", "rate", "stopped", "done", "failedTail", "limited"):
            assert "{n}" in text, (lang, key)
        if key == "extName":
            assert len(text) <= 75, lang
        if key == "extDesc":
            assert len(text) <= 132, (lang, len(text))
        data[key] = entry
    os.makedirs(os.path.join(root, lang), exist_ok=True)
    with open(os.path.join(root, lang, "messages.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
print("locales:", ", ".join(L))
